-- CTE NAME: mi_vw

SELECT
  m.BANK_TO_BANK_TRNFR_FL,
  m.BENEF_ACCT_ID,
  m.BENEF_ACTVY_RISK_NB,
  m.CLR_TRXN_ACTVY_AM,
  m.CXL_PAIR_TRXN_INTRL_ID,
  m.DATA_DUMP_DT,
  m.DEP_TRXN_ACTVY_AM,
  m.FO_TRXN_SEQ_ID,
  m.INTRL_BENEF_ACCT_FL,
  m.INTRL_REM_ACCT_FL,
  m.INTRL_SCND_BENEF_ACCT_FL,
  m.ISSUE_TRXN_ACTVY_AM,
  m.MANTAS_ISSUE_DATE,
  m.MANTAS_POST_DT,
  m.MANTAS_TRXN_PRDCT_CD,
  m.MANTAS_TRXN_PURP_CD,
  m.PASS_THRU_FL,
  m.REM_ACCT_ID,
  m.REM_ACTVY_RISK_NB,
  m.SCND_BENEF_ACCT_ID,
  m.SCND_BENEF_ACTVY_RISK_NB,
  m.SRC_SYS_CD,
  m.TRSTD_TRXN_FL,
  m.TRXN_BASE_AM,
  DECODE('B', 'F', m.TRXN_FUNC_AM, m.TRXN_BASE_AM) AS Trxn_Am,
  m.UNRLTD_PARTY_FL,
  CASE
    WHEN m.PASS_THRU_FL = 'Y'
    THEN DECODE('B', 'F', m.TRXN_FUNC_AM, m.TRXN_BASE_AM)
    ELSE 0
  END AS Pass_Thru_Am,
  CASE
    WHEN DECODE('B', 'F', m.TRXN_FUNC_AM, m.TRXN_BASE_AM) - TRUNC(DECODE('B', 'F', m.TRXN_FUNC_AM, m.TRXN_BASE_AM), -4) = 0
    THEN DECODE('B', 'F', m.TRXN_FUNC_AM, m.TRXN_BASE_AM)
    WHEN m.DEP_TRXN_ACTVY_AM - TRUNC(m.DEP_TRXN_ACTVY_AM, -4) = 0
    THEN DECODE('B', 'F', m.TRXN_FUNC_AM, m.TRXN_BASE_AM)
    WHEN m.ISSUE_TRXN_ACTVY_AM - TRUNC(m.ISSUE_TRXN_ACTVY_AM, -4) = 0
    THEN DECODE('B', 'F', m.TRXN_FUNC_AM, m.TRXN_BASE_AM)
    WHEN m.CLR_TRXN_ACTVY_AM - TRUNC(m.CLR_TRXN_ACTVY_AM, -4) = 0
    THEN DECODE('B', 'F', m.TRXN_FUNC_AM, m.TRXN_BASE_AM)
    ELSE 0
  END AS Lrf_Am,
  CASE
    WHEN m.TRSTD_TRXN_FL = 'Y'
    THEN DECODE('B', 'F', m.TRXN_FUNC_AM, m.TRXN_BASE_AM)
    ELSE 0
  END AS Trusted_Trans_Amt,
  m.FUNC_CRNCY_CD
FROM fccmatomic.MI_TRXN m
WHERE
  m.MANTAS_TRXN_PURP_CD = 'GENERAL'
  AND m.MANTAS_TRXN_PRDCT_CD IN (
    'CASH-EQ-CASHIER-CHECK',
    'CASH-EQ-CERT-CHECK',
    'CASH-EQ-MONEY-ORDER',
    'CASH-EQ-TRAVELERS-CHECK',
    'CASH-EQ-OTHER',
    'CASH-LETTER',
    'CHECK',
    'PAPER-OTHER',
    'CHECK-ACH'
  )
  AND (
    'Y' = 'Y' OR m.SRC_SYS_CD IN ('Inactive')
  )
  AND /* 20039324, 34237111 */ m.DATA_DUMP_DT > (
    SELECT
      Min_Dt
    FROM clndr_vw
  )
  AND m.DATA_DUMP_DT <= (
    SELECT
      Max_Dt
    FROM clndr_vw
  )
  AND (
    'Y' = 'Y' OR NOT (
      m.BANK_TO_BANK_TRNFR_FL = 'Y' AND m.PASS_THRU_FL = 'N'
    )
  )
  AND /* 21034264 */ (
    'Y' = 'Y' OR COALESCE(m.TRSTD_TRXN_FL, 'N') = 'N'
  )
  AND (
    'Y' = 'Y' OR COALESCE(m.unrltd_party_fl, 'Y') <> 'N'
  )
  AND m.CXL_PAIR_TRXN_INTRL_ID IS NULL