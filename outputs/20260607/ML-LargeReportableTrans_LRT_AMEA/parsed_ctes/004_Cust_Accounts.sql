-- CTE NAME: Cust_Accounts

SELECT
  c.CUST_SEQ_ID,
  ac.PRMRY_CUST_INTRL_ID AS CUST_ID,
  ac.ACCT_INTRL_ID,
  c.CUST_EFCTV_RISK_NB,
  MIN(ac.ACCT_OPEN_DT) OVER (PARTITION BY c.CUST_SEQ_ID) AS Min_Acct_Open_Dt
FROM fccmatomic.ACCT ac, fccmatomic.CUST c
WHERE
  c.CUST_INTRL_ID = ac.PRMRY_CUST_INTRL_ID
  AND ac.MANTAS_ACCT_HOLDR_TYPE_CD IN ('CR')
  AND c.CUST_EFCTV_RISK_NB <> -2
  AND ac.MANTAS_ACCT_BUS_TYPE_CD IN ('RBK', 'RBR')
  AND (
    'N' = 'Y' OR c.JRSDCN_CD IN ('AMEA')
  )
  AND 'Y' = 'Y'
UNION ALL
SELECT
  c.CUST_SEQ_ID,
  c.CUST_INTRL_ID AS CUST_ID,
  ac.ACCT_INTRL_ID,
  c.CUST_EFCTV_RISK_NB,
  MIN(ac.ACCT_OPEN_DT) OVER (PARTITION BY c.CUST_SEQ_ID) AS Min_Acct_Open_Dt
FROM fccmatomic.ACCT ac, fccmatomic.CUST_ACCT ca, fccmatomic.CUST c, fccmatomic.CUST_ACCT_ROLE car
WHERE
  ac.ACCT_INTRL_ID = ca.ACCT_INTRL_ID
  AND ca.CUST_INTRL_ID = c.CUST_INTRL_ID
  AND ca.CUST_ACCT_ROLE_CD = car.CUST_ACCT_ROLE_CD
  AND ac.MANTAS_ACCT_HOLDR_TYPE_CD IN ('CR')
  AND c.CUST_EFCTV_RISK_NB <> -2
  AND ac.MANTAS_ACCT_BUS_TYPE_CD IN ('RBK', 'RBR')
  AND (
    'N' = 'Y' OR c.JRSDCN_CD IN ('AMEA')
  )
  AND (
    car.TRDNG_AUTH_FL = 'Y' OR car.WDRWL_AUTH_FL = 'Y' OR car.POA_FL = 'Y'
  )
  AND 'Y' = 'N'